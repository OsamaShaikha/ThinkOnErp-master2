using Oracle.ManagedDataAccess.Client;

internal static class HrLeavePolicySchema
{
    private static readonly HrSchemaColumnExpectation[] EffectiveDateColumns =
    [
        new("HR_LEAVE_POLICY", "EFFECTIVE_FROM", "TIMESTAMP(7)", "*", Additive: true),
        new("HR_LEAVE_POLICY", "EFFECTIVE_TO", "TIMESTAMP(7)", "*", Additive: true)
    ];

    public static async Task Install(OracleConnection connection, List<string> report)
    {
        async Task<long> Count(string sql)
        {
            await using var command = connection.CreateCommand();
            command.CommandText = sql;
            command.CommandTimeout = 30;
            return Convert.ToInt64(await command.ExecuteScalarAsync());
        }

        async Task Run(string sql)
        {
            await using var command = connection.CreateCommand();
            command.CommandText = sql;
            command.CommandTimeout = 30;
            await command.ExecuteNonQueryAsync();
        }

        await PreflightAsync(connection);
        if (await Count("SELECT COUNT(*) FROM ALL_TABLES WHERE OWNER='DEV_TEMPLATE' AND TABLE_NAME='HR_LEAVE_POLICY'") == 0)
        {
            await Run("CREATE TABLE DEV_TEMPLATE.HR_LEAVE_POLICY (ID NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY, POLICY_NAME NVARCHAR2(200) NOT NULL, LEAVE_TYPE_CODE NVARCHAR2(50) NOT NULL, EFFECTIVE_FROM TIMESTAMP(7) NOT NULL, EFFECTIVE_TO TIMESTAMP(7) NULL, ACCRUAL_METHOD NVARCHAR2(50) NOT NULL, ACCRUAL_RATE NUMBER(8,4) NOT NULL, ANNUAL_ENTITLEMENT_DAYS NUMBER(8,4) NULL, CYCLE_BASIS NVARCHAR2(40) NOT NULL, PRORATE_FIRST_CYCLE NUMBER(10) NOT NULL, APPLICABLE_TO NVARCHAR2(50) NOT NULL, MIN_SERVICE_MONTHS NUMBER(10) NOT NULL, TIER1_YEARS_THRESHOLD NUMBER(10) NOT NULL, TIER1_DAYS NUMBER(6,2) NOT NULL, TIER2_DAYS NUMBER(6,2) NOT NULL, IS_ACTIVE NUMBER(10) NOT NULL, CREATION_USER NVARCHAR2(100) NOT NULL, CREATION_DATE TIMESTAMP(7) NOT NULL, UPDATE_USER NVARCHAR2(100) NULL, UPDATE_DATE TIMESTAMP(7) NULL, CONSTRAINT PK_HR_LEAVE_POLICY PRIMARY KEY (ID), CONSTRAINT FK_HR_LEAVE_POLICY_TYPE FOREIGN KEY (LEAVE_TYPE_CODE) REFERENCES DEV_TEMPLATE.HR_LEAVE_TYPE(LEAVE_TYPE_CODE))");
            report.Add("Created HR_LEAVE_POLICY from the mapped schema; the table starts empty and receives no guessed policy rows.");
        }
        if (await Count("SELECT COUNT(*) FROM ALL_TAB_COLS WHERE OWNER='DEV_TEMPLATE' AND TABLE_NAME='HR_LEAVE_POLICY' AND COLUMN_NAME='EFFECTIVE_FROM'") == 0)
            await Run("ALTER TABLE DEV_TEMPLATE.HR_LEAVE_POLICY ADD (EFFECTIVE_FROM TIMESTAMP(7) NULL)");
        if (await Count("SELECT COUNT(*) FROM ALL_TAB_COLS WHERE OWNER='DEV_TEMPLATE' AND TABLE_NAME='HR_LEAVE_POLICY' AND COLUMN_NAME='EFFECTIVE_TO'") == 0)
            await Run("ALTER TABLE DEV_TEMPLATE.HR_LEAVE_POLICY ADD (EFFECTIVE_TO TIMESTAMP(7) NULL)");
        await HrSchemaColumnGuard.ValidateAsync(connection, EffectiveDateColumns, allowMissingColumns: false);
        await Run("UPDATE DEV_TEMPLATE.HR_LEAVE_POLICY SET EFFECTIVE_FROM=TRUNC(CREATION_DATE) WHERE EFFECTIVE_FROM IS NULL");
        if (await Count("SELECT COUNT(*) FROM DEV_TEMPLATE.HR_LEAVE_POLICY WHERE EFFECTIVE_FROM IS NULL") > 0)
            throw new InvalidOperationException("Leave policy effective dates could not be backfilled; manual review is required.");
        await Run("ALTER TABLE DEV_TEMPLATE.HR_LEAVE_POLICY MODIFY (EFFECTIVE_FROM NOT NULL)");
        await HrSchemaColumnGuard.ValidateAsync(connection,
        [
            new("HR_LEAVE_POLICY", "EFFECTIVE_FROM", "TIMESTAMP(7)", "N"),
            new("HR_LEAVE_POLICY", "EFFECTIVE_TO", "TIMESTAMP(7)", "Y")
        ], allowMissingColumns: false);
        var existingIndex = await Count("SELECT COUNT(*) FROM ALL_INDEXES WHERE OWNER='DEV_TEMPLATE' AND INDEX_NAME='IX_HR_LEAVE_POLICY_EFFECTIVE'");
        if (existingIndex == 0)
            await Run("CREATE INDEX DEV_TEMPLATE.IX_HR_LEAVE_POLICY_EFFECTIVE ON DEV_TEMPLATE.HR_LEAVE_POLICY (LEAVE_TYPE_CODE,EFFECTIVE_FROM)");
        await VerifyEffectiveIndex(connection);
        report.Add("Ensured HR_LEAVE_POLICY bootstrap/effective dates and the leave-type/date lookup index; existing rows start on their creation date.");
    }

    public static async Task PreflightAsync(OracleConnection connection)
    {
        await PreflightCreateAsync(connection);
        await using var table = connection.CreateCommand();
        table.CommandText = "SELECT COUNT(*) FROM ALL_TABLES WHERE OWNER='DEV_TEMPLATE' AND TABLE_NAME='HR_LEAVE_POLICY'";
        table.CommandTimeout = 30;
        var tableCount = Convert.ToInt64(await table.ExecuteScalarAsync());
        if (tableCount == 0) return;
        await HrSchemaColumnGuard.ValidateAsync(connection,
            [new("HR_LEAVE_POLICY", "CREATION_DATE", "TIMESTAMP(7)", "N")], allowMissingColumns: false);
        await HrSchemaColumnGuard.ValidateAsync(connection, EffectiveDateColumns, allowMissingColumns: true);
        await PreflightEffectiveIndex(connection);
        await PreflightEffectiveDateBackfill(connection);
    }

    public static async Task PreflightCreateAsync(OracleConnection connection)
    {
        async Task<long> Count(string sql)
        {
            await using var command = connection.CreateCommand();
            command.CommandText = sql;
            command.CommandTimeout = 30;
            return Convert.ToInt64(await command.ExecuteScalarAsync());
        }

        var tableCount = await Count("SELECT COUNT(*) FROM ALL_TABLES WHERE OWNER='DEV_TEMPLATE' AND TABLE_NAME='HR_LEAVE_POLICY'");
        if (tableCount == 1) return;
        if (tableCount > 1)
            throw new InvalidOperationException("DEV_TEMPLATE.HR_LEAVE_POLICY has ambiguous table metadata; no DDL applied.");

        if (await Count("SELECT COUNT(*) FROM ALL_OBJECTS WHERE OWNER='DEV_TEMPLATE' AND OBJECT_NAME='HR_LEAVE_POLICY'") != 0)
            throw new InvalidOperationException("DEV_TEMPLATE.HR_LEAVE_POLICY is reserved by a non-table object; no DDL applied.");

        if (await Count("SELECT COUNT(*) FROM ALL_TABLES WHERE OWNER='DEV_TEMPLATE' AND TABLE_NAME='HR_LEAVE_TYPE'") != 1 ||
            await Count("SELECT COUNT(*) FROM ALL_TAB_COLS WHERE OWNER='DEV_TEMPLATE' AND TABLE_NAME='HR_LEAVE_TYPE' AND COLUMN_NAME='LEAVE_TYPE_CODE' AND DATA_TYPE='NVARCHAR2' AND CHAR_LENGTH>=50 AND NULLABLE='N' AND NVL(DEFAULT_LENGTH,0)=0 AND VIRTUAL_COLUMN='NO'") != 1 ||
            await Count("SELECT COUNT(*) FROM ALL_CONSTRAINTS c WHERE c.OWNER='DEV_TEMPLATE' AND c.TABLE_NAME='HR_LEAVE_TYPE' AND c.CONSTRAINT_TYPE IN ('P','U') AND c.STATUS='ENABLED' AND c.VALIDATED='VALIDATED' AND (SELECT COUNT(*) FROM ALL_CONS_COLUMNS cc WHERE cc.OWNER=c.OWNER AND cc.CONSTRAINT_NAME=c.CONSTRAINT_NAME)=1 AND EXISTS (SELECT 1 FROM ALL_CONS_COLUMNS cc WHERE cc.OWNER=c.OWNER AND cc.CONSTRAINT_NAME=c.CONSTRAINT_NAME AND cc.COLUMN_NAME='LEAVE_TYPE_CODE' AND cc.POSITION=1)") != 1)
            throw new InvalidOperationException("HR_LEAVE_TYPE.LEAVE_TYPE_CODE lacks the expected enabled parent key; HR_LEAVE_POLICY creation stopped before DDL.");

        foreach (var name in new[] { "PK_HR_LEAVE_POLICY", "FK_HR_LEAVE_POLICY_TYPE", "IX_HR_LEAVE_POLICY_EFFECTIVE" })
        {
            if (await Count($"SELECT (SELECT COUNT(*) FROM ALL_CONSTRAINTS WHERE OWNER='DEV_TEMPLATE' AND CONSTRAINT_NAME='{name}') + (SELECT COUNT(*) FROM ALL_INDEXES WHERE OWNER='DEV_TEMPLATE' AND INDEX_NAME='{name}') FROM DUAL") != 0)
                throw new InvalidOperationException($"{name} is already reserved by another object; HR_LEAVE_POLICY creation stopped before DDL.");
        }
    }

    public static async Task Verify(OracleConnection connection, List<string> report)
    {
        await HrSchemaColumnGuard.ValidateAsync(connection,
        [
            new("HR_LEAVE_POLICY", "EFFECTIVE_FROM", "TIMESTAMP(7)", "N"),
            new("HR_LEAVE_POLICY", "EFFECTIVE_TO", "TIMESTAMP(7)", "Y")
        ], allowMissingColumns: false);
        async Task<List<string[]>> Query(string sql)
        {
            await using var command = connection.CreateCommand();
            command.CommandText = sql;
            command.CommandTimeout = 15;
            await using var reader = await command.ExecuteReaderAsync();
            var rows = new List<string[]>();
            while (await reader.ReadAsync())
                rows.Add(Enumerable.Range(0, reader.FieldCount).Select(i => reader.IsDBNull(i) ? "NULL" : reader.GetValue(i).ToString()!).ToArray());
            return rows;
        }

        var policyColumns = await Query("SELECT COLUMN_NAME,DATA_TYPE,NULLABLE FROM ALL_TAB_COLS WHERE OWNER='DEV_TEMPLATE' AND TABLE_NAME='HR_LEAVE_POLICY' AND COLUMN_NAME IN ('EFFECTIVE_FROM','EFFECTIVE_TO') ORDER BY COLUMN_NAME");
        if (policyColumns.Count != 2 || !policyColumns.Any(c => c[0] == "EFFECTIVE_FROM" && c[2] == "N") || !policyColumns.Any(c => c[0] == "EFFECTIVE_TO" && c[2] == "Y"))
            throw new InvalidOperationException("DEV_TEMPLATE HR_LEAVE_POLICY effective-date columns are missing or have unexpected nullability.");
        await Query("SELECT EFFECTIVE_FROM,EFFECTIVE_TO FROM DEV_TEMPLATE.HR_LEAVE_POLICY WHERE 1=0");
        report.Add("HR_LEAVE_POLICY effective dates, nullable end date, lookup index and mapped SELECT verified.");
    }

    private static async Task PreflightEffectiveIndex(OracleConnection connection)
    {
        await using var command = connection.CreateCommand();
        command.CommandText = "SELECT TABLE_NAME,UNIQUENESS,STATUS FROM ALL_INDEXES WHERE OWNER='DEV_TEMPLATE' AND INDEX_NAME='IX_HR_LEAVE_POLICY_EFFECTIVE'";
        await using var reader = await command.ExecuteReaderAsync();
        if (!await reader.ReadAsync()) return;
        var table = reader.GetString(0);
        var uniqueness = reader.GetString(1);
        var status = reader.GetString(2);
        if (await reader.ReadAsync())
            throw new InvalidOperationException("IX_HR_LEAVE_POLICY_EFFECTIVE has ambiguous metadata; leave policy repair stopped before DDL.");
        await reader.DisposeAsync();
        if (table != "HR_LEAVE_POLICY" || uniqueness != "NONUNIQUE" || status != "VALID" ||
            await CountIndexColumns(connection, "IX_HR_LEAVE_POLICY_EFFECTIVE") != "LEAVE_TYPE_CODE,EFFECTIVE_FROM")
            throw new InvalidOperationException("IX_HR_LEAVE_POLICY_EFFECTIVE is reserved by another object or has an incompatible definition; leave policy repair stopped before DDL.");
    }

    private static async Task PreflightEffectiveDateBackfill(OracleConnection connection)
    {
        await using var column = connection.CreateCommand();
        column.CommandText = "SELECT COUNT(*) FROM ALL_TAB_COLS WHERE OWNER='DEV_TEMPLATE' AND TABLE_NAME='HR_LEAVE_POLICY' AND COLUMN_NAME='EFFECTIVE_FROM'";
        var effectiveFromExists = Convert.ToInt32(await column.ExecuteScalarAsync()) != 0;
        await using var invalid = connection.CreateCommand();
        invalid.CommandText = effectiveFromExists
            ? "SELECT COUNT(*) FROM DEV_TEMPLATE.HR_LEAVE_POLICY WHERE EFFECTIVE_FROM IS NULL AND CREATION_DATE IS NULL"
            : "SELECT COUNT(*) FROM DEV_TEMPLATE.HR_LEAVE_POLICY WHERE CREATION_DATE IS NULL";
        if (Convert.ToInt64(await invalid.ExecuteScalarAsync()) != 0)
            throw new InvalidOperationException("HR_LEAVE_POLICY has rows that cannot be dated from CREATION_DATE; leave policy repair stopped before DDL.");
    }

    private static async Task VerifyEffectiveIndex(OracleConnection connection)
    {
        await using var command = connection.CreateCommand();
        command.CommandText = "SELECT COUNT(*) FROM ALL_INDEXES i WHERE i.OWNER='DEV_TEMPLATE' AND i.INDEX_NAME='IX_HR_LEAVE_POLICY_EFFECTIVE' AND i.TABLE_NAME='HR_LEAVE_POLICY' AND i.UNIQUENESS='NONUNIQUE' AND i.STATUS='VALID'";
        var valid = Convert.ToInt64(await command.ExecuteScalarAsync()) == 1;
        var columns = await CountIndexColumns(connection, "IX_HR_LEAVE_POLICY_EFFECTIVE");
        if (!valid || columns != "LEAVE_TYPE_CODE,EFFECTIVE_FROM")
            throw new InvalidOperationException("IX_HR_LEAVE_POLICY_EFFECTIVE is missing or does not match its expected valid definition.");
    }

    private static async Task<string> CountIndexColumns(OracleConnection connection, string indexName)
    {
        await using var command = connection.CreateCommand();
        command.CommandText = "SELECT LISTAGG(COLUMN_NAME, ',') WITHIN GROUP (ORDER BY COLUMN_POSITION) FROM ALL_IND_COLUMNS WHERE INDEX_OWNER='DEV_TEMPLATE' AND INDEX_NAME=:indexName";
        command.Parameters.Add(new OracleParameter("indexName", indexName));
        return Convert.ToString(await command.ExecuteScalarAsync()) ?? string.Empty;
    }
}
