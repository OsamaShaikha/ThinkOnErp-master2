COL TABLE_NAME FORMAT A30;
COL COLUMN_NAME FORMAT A30;
COL DATA_TYPE FORMAT A15;
COL DATA_LENGTH FORMAT 9999;
COL DATA_PRECISION FORMAT 999;
COL DATA_SCALE FORMAT 99;
COL NULLABLE FORMAT A4;
COL DATA_DEFAULT FORMAT A30;

SPOOL d:\ThinkOnErp\artifacts\dev_template_hr_schema_full.txt;

PROMPT ==============================================================================;
PROMPT HR TABLES IN DEV_TEMPLATE;
PROMPT ==============================================================================;

SELECT TABLE_NAME 
FROM ALL_TABLES 
WHERE OWNER = 'DEV_TEMPLATE' AND TABLE_NAME LIKE 'HR%'
ORDER BY TABLE_NAME;

PROMPT ==============================================================================;
PROMPT COLUMNS FOR ALL HR TABLES;
PROMPT ==============================================================================;

SELECT TABLE_NAME, COLUMN_ID, COLUMN_NAME, DATA_TYPE, DATA_LENGTH, DATA_PRECISION, DATA_SCALE, NULLABLE, DATA_DEFAULT
FROM ALL_TAB_COLUMNS
WHERE OWNER = 'DEV_TEMPLATE' AND TABLE_NAME LIKE 'HR%'
ORDER BY TABLE_NAME, COLUMN_ID;

PROMPT ==============================================================================;
PROMPT PRIMARY KEYS AND CONSTRAINTS FOR HR TABLES;
PROMPT ==============================================================================;

COL CONSTRAINT_NAME FORMAT A30;
COL CONSTRAINT_TYPE FORMAT A5;
COL SEARCH_CONDITION FORMAT A40;
COL R_CONSTRAINT_NAME FORMAT A30;
COL REF_TABLE FORMAT A30;

SELECT c.TABLE_NAME, c.CONSTRAINT_NAME, c.CONSTRAINT_TYPE, c.SEARCH_CONDITION, c.R_CONSTRAINT_NAME,
       (SELECT r.TABLE_NAME FROM ALL_CONSTRAINTS r WHERE r.OWNER = c.R_OWNER AND r.CONSTRAINT_NAME = c.R_CONSTRAINT_NAME) as REF_TABLE
FROM ALL_CONSTRAINTS c
WHERE c.OWNER = 'DEV_TEMPLATE' AND c.TABLE_NAME LIKE 'HR%'
ORDER BY c.TABLE_NAME, c.CONSTRAINT_TYPE, c.CONSTRAINT_NAME;

PROMPT ==============================================================================;
PROMPT CONSTRAINT COLUMNS;
PROMPT ==============================================================================;

COL POSITION FORMAT 99;
SELECT cc.TABLE_NAME, cc.CONSTRAINT_NAME, cc.COLUMN_NAME, cc.POSITION
FROM ALL_CONS_COLUMNS cc
JOIN ALL_CONSTRAINTS c ON cc.OWNER = c.OWNER AND cc.CONSTRAINT_NAME = c.CONSTRAINT_NAME
WHERE cc.OWNER = 'DEV_TEMPLATE' AND cc.TABLE_NAME LIKE 'HR%' AND c.CONSTRAINT_TYPE IN ('P', 'R', 'U')
ORDER BY cc.TABLE_NAME, cc.CONSTRAINT_NAME, cc.POSITION;

PROMPT ==============================================================================;
PROMPT SEQUENCES RELATED TO HR IN DEV_TEMPLATE OR THINKON_ERP;
PROMPT ==============================================================================;

COL SEQUENCE_OWNER FORMAT A20;
COL SEQUENCE_NAME FORMAT A30;

SELECT SEQUENCE_OWNER, SEQUENCE_NAME, MIN_VALUE, MAX_VALUE, INCREMENT_BY, LAST_NUMBER
FROM ALL_SEQUENCES
WHERE (SEQUENCE_OWNER IN ('DEV_TEMPLATE', 'THINKON_ERP') AND SEQUENCE_NAME LIKE '%HR%')
   OR (SEQUENCE_OWNER IN ('DEV_TEMPLATE', 'THINKON_ERP') AND SEQUENCE_NAME LIKE '%PAYROLL%')
ORDER BY SEQUENCE_OWNER, SEQUENCE_NAME;

