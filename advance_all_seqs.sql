DECLARE
  v_max_id NUMBER;
BEGIN
  FOR t IN (SELECT table_name FROM user_tables WHERE table_name IN (SYS_BRANCH_SYSTEMS, SYS_ROLE_SCREEN_PERMISSIONS, SYS_USER_SCREEN_PERMISSIONS, SYS_USERS_ROLES, SYS_FISCAL_YEAR, SYS_BRANCH, SYS_USERS, SYS_REQUEST_TICKET, SYS_TICKET_COMMENT, SYS_TICKET_ATTACHMENT, SYS_DOCUMENT, SYS_SAVED_SEARCH, SYS_SLOW_QUERIES, SYS_SECURITY_THREATS, SYS_FAILED_LOGINS, SYS_PERFORMANCE_METRICS, SYS_AUDIT_LOG_ARCHIVE)) LOOP
    BEGIN
      EXECUTE IMMEDIATE 'SELECT MAX("Id") FROM "' || t.table_name || '"' INTO v_max_id;
      IF v_max_id IS NOT NULL THEN
        EXECUTE IMMEDIATE 'ALTER TABLE "' || t.table_name || '" MODIFY ("Id" GENERATED BY DEFAULT AS IDENTITY (START WITH ' || (v_max_id + 1) || '))';
        DBMS_OUTPUT.PUT_LINE(t.table_name || ': advanced to ' || (v_max_id + 1));
      END IF;
    EXCEPTION
      WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE(t.table_name || ': skipped (' || SQLERRM || ')');
    END;
  END LOOP;
END;
/
EXIT;
