DECLARE
  v_max_id NUMBER;
BEGIN
  SELECT MAX("Id") INTO v_max_id FROM "SYS_BRANCH_SCREEN_PERMISSIONS";
  EXECUTE IMMEDIATE 'ALTER TABLE "SYS_BRANCH_SCREEN_PERMISSIONS" MODIFY ("Id" GENERATED BY DEFAULT AS IDENTITY (START WITH ' || (v_max_id + 1) || '))';
  DBMS_OUTPUT.PUT_LINE('Identity advanced to start with: ' || (v_max_id + 1));
END;
/
EXIT;
