-- ============================================================================
-- Script: 127_Fix_SYS_SYSTEM_SCREEN_Sequence_And_Triggers.sql
-- Description: Fixes SYS_SYSTEM_SCREEN identity / sequence auto-generation
--              in THINKON_ERP and DEV_TEMPLATE to prevent ORA-01400 on screen-system linking.
-- ============================================================================

-- 1. Ensure Sequence Exists in THINKON_ERP
DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM ALL_SEQUENCES WHERE SEQUENCE_NAME = 'SEQ_SYS_SYSTEM_SCREEN' AND SEQUENCE_OWNER = 'THINKON_ERP';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE SEQUENCE THINKON_ERP.SEQ_SYS_SYSTEM_SCREEN START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE';
    END IF;
END;
/

-- 2. Set DEFAULT ON NULL Sequence on THINKON_ERP.SYS_SYSTEM_SCREEN."Id"
BEGIN
    EXECUTE IMMEDIATE 'ALTER TABLE THINKON_ERP.SYS_SYSTEM_SCREEN MODIFY "Id" NUMBER(19) DEFAULT ON NULL THINKON_ERP.SEQ_SYS_SYSTEM_SCREEN.NEXTVAL';
EXCEPTION
    WHEN OTHERS THEN
        NULL;
END;
/

-- 3. Create Trigger TRG_SYS_SYSTEM_SCREEN_ID on THINKON_ERP
CREATE OR REPLACE TRIGGER THINKON_ERP.TRG_SYS_SYSTEM_SCREEN_ID
BEFORE INSERT ON THINKON_ERP.SYS_SYSTEM_SCREEN
FOR EACH ROW
BEGIN
    IF :NEW."Id" IS NULL OR :NEW."Id" <= 0 THEN
        :NEW."Id" := THINKON_ERP.SEQ_SYS_SYSTEM_SCREEN.NEXTVAL;
    END IF;
END;
/

-- 4. Ensure Sequence Exists in DEV_TEMPLATE
DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM ALL_SEQUENCES WHERE SEQUENCE_NAME = 'SEQ_SYS_SYSTEM_SCREEN' AND SEQUENCE_OWNER = 'DEV_TEMPLATE';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE SEQUENCE DEV_TEMPLATE.SEQ_SYS_SYSTEM_SCREEN START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE';
    END IF;
END;
/

-- 5. Create Trigger TRG_SYS_SYSTEM_SCREEN_ID on DEV_TEMPLATE
CREATE OR REPLACE TRIGGER DEV_TEMPLATE.TRG_SYS_SYSTEM_SCREEN_ID
BEFORE INSERT ON DEV_TEMPLATE.SYS_SYSTEM_SCREEN
FOR EACH ROW
BEGIN
    IF :NEW."Id" IS NULL OR :NEW."Id" <= 0 THEN
        :NEW."Id" := DEV_TEMPLATE.SEQ_SYS_SYSTEM_SCREEN.NEXTVAL;
    END IF;
END;
/
