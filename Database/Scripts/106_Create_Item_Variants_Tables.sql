-- 5. Create INV_ITEM_VARIANT_VALUE
BEGIN
    EXECUTE IMMEDIATE '
    CREATE TABLE "INV_ITEM_VARIANT_VALUE" (
        "ID" NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
        "VARIANT_ID" NUMBER(19) NOT NULL,
        "ATTRIBUTE_ID" NUMBER(19) NOT NULL,
        "ATTRIBUTE_VALUE_ID" NUMBER(19) NOT NULL,
        CONSTRAINT "FK_INV_VARVAL_VARIANT" FOREIGN KEY ("VARIANT_ID") REFERENCES "INV_ITEM_VARIANT"("ID") ON DELETE CASCADE,
        CONSTRAINT "FK_INV_VARVAL_ATTR" FOREIGN KEY ("ATTRIBUTE_ID") REFERENCES "INV_ITEM_ATTRIBUTE"("ID"),
        CONSTRAINT "FK_INV_VARVAL_VALUE" FOREIGN KEY ("ATTRIBUTE_VALUE_ID") REFERENCES "INV_ITEM_ATTRIBUTE_VALUE"("ID"),
        CONSTRAINT "UQ_INV_VARVAL_COMBO" UNIQUE ("VARIANT_ID", "ATTRIBUTE_ID")
    )';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -955 THEN NULL; ELSE RAISE; END IF;
END;
