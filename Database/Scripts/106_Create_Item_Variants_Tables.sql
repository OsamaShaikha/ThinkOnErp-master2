-- Seed Common Attributes (Color, Size) for Branch 1
MERGE INTO "INV_ITEM_ATTRIBUTE" t
USING (SELECT 1 AS b, 'COLOR' AS c FROM dual) s
ON (t."BRANCH_ID" = s.b AND t."ATTRIBUTE_CODE" = s.c)
WHEN NOT MATCHED THEN
    INSERT ("BRANCH_ID", "ATTRIBUTE_CODE", "NAME_LOCAL", "NAME_EN", "IS_ACTIVE", "CREATION_USER", "CREATION_DATE")
    VALUES (1, 'COLOR', N'اللون', 'Color', 1, 'SYSTEM', SYSTIMESTAMP);

MERGE INTO "INV_ITEM_ATTRIBUTE" t
