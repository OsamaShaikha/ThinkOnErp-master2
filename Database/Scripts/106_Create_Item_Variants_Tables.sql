-- 1. Alter INV_ITEM to add SKU and HAS_VARIANTS columns if not exist
BEGIN
    EXECUTE IMMEDIATE 'ALTER TABLE "INV_ITEM" ADD ("SKU" NVARCHAR2(100) NULL)';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -1430 THEN NULL; ELSE RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE 'ALTER TABLE "INV_ITEM" ADD ("HAS_VARIANTS" NUMBER(1) DEFAULT 0 NOT NULL)';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -1430 THEN NULL; ELSE RAISE; END IF;
END;
/

-- 2. Create INV_ITEM_ATTRIBUTE
BEGIN
    EXECUTE IMMEDIATE '
    CREATE TABLE "INV_ITEM_ATTRIBUTE" (
        "ID" NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
        "BRANCH_ID" NUMBER(19) NOT NULL,
        "ATTRIBUTE_CODE" NVARCHAR2(50) NOT NULL,
        "NAME_LOCAL" NVARCHAR2(100) NOT NULL,
        "NAME_EN" NVARCHAR2(100) NULL,
        "IS_ACTIVE" NUMBER(1) DEFAULT 1 NOT NULL,
        "CREATION_USER" NVARCHAR2(100) NOT NULL,
        "CREATION_DATE" TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
        CONSTRAINT "UQ_INV_ITEM_ATTR_CODE" UNIQUE ("BRANCH_ID", "ATTRIBUTE_CODE")
    )';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -955 THEN NULL; ELSE RAISE; END IF;
END;
/

-- 3. Create INV_ITEM_ATTRIBUTE_VALUE
BEGIN
    EXECUTE IMMEDIATE '
    CREATE TABLE "INV_ITEM_ATTRIBUTE_VALUE" (
        "ID" NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
        "ATTRIBUTE_ID" NUMBER(19) NOT NULL,
        "VALUE_CODE" NVARCHAR2(50) NOT NULL,
        "VALUE_LOCAL" NVARCHAR2(100) NOT NULL,
        "VALUE_EN" NVARCHAR2(100) NULL,
        "COLOR_HEX" NVARCHAR2(20) NULL,
        "SORT_ORDER" NUMBER(6) DEFAULT 0 NOT NULL,
        "IS_ACTIVE" NUMBER(1) DEFAULT 1 NOT NULL,
        CONSTRAINT "FK_INV_ATTRVAL_ATTR" FOREIGN KEY ("ATTRIBUTE_ID") REFERENCES "INV_ITEM_ATTRIBUTE"("ID") ON DELETE CASCADE,
        CONSTRAINT "UQ_INV_ATTRVAL_CODE" UNIQUE ("ATTRIBUTE_ID", "VALUE_CODE")
    )';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -955 THEN NULL; ELSE RAISE; END IF;
END;
/

-- 4. Create INV_ITEM_VARIANT
BEGIN
    EXECUTE IMMEDIATE '
    CREATE TABLE "INV_ITEM_VARIANT" (
        "ID" NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
        "ITEM_ID" NUMBER(19) NOT NULL,
        "SKU" NVARCHAR2(100) NOT NULL,
        "VARIANT_NAME_LOCAL" NVARCHAR2(255) NOT NULL,
        "VARIANT_NAME_EN" NVARCHAR2(255) NULL,
        "BARCODE" NVARCHAR2(100) NULL,
        "ADDITIONAL_PRICE" NUMBER(18, 4) DEFAULT 0 NOT NULL,
        "COST_PRICE" NUMBER(18, 4) DEFAULT 0 NOT NULL,
        "IMAGE_BASE64" CLOB NULL,
        "IS_ACTIVE" NUMBER(1) DEFAULT 1 NOT NULL,
        "CREATION_USER" NVARCHAR2(100) NOT NULL,
        "CREATION_DATE" TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
        "UPDATE_USER" NVARCHAR2(100) NULL,
        "UPDATE_DATE" TIMESTAMP NULL,
        CONSTRAINT "FK_INV_VARIANT_ITEM" FOREIGN KEY ("ITEM_ID") REFERENCES "INV_ITEM"("ID") ON DELETE CASCADE
    )';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -955 THEN NULL; ELSE RAISE; END IF;
END;
/

