-- ==============================================================================
-- 122_Create_Pos_Branch_Settings_Table.sql
-- Creates POS_BRANCH_SETTING table to support branch-specific POS default GL accounts
-- and default warehouse settings:
--   - BRANCH_ID (Unique per branch)
--   - DEFAULT_CASH_ACCOUNT
--   - DEFAULT_EXPENSE_ACCOUNT
--   - DEFAULT_RECEIPT_ACCOUNT
--   - DEFAULT_WAREHOUSE_ID
-- ==============================================================================

DECLARE
    v_cnt NUMBER;
BEGIN
    FOR s IN (
        SELECT owner 
        FROM all_tables 
        WHERE table_name = 'SYS_BRANCH' 
          AND (owner = 'DEV_TEMPLATE' OR owner LIKE 'THINKONERP_%')
        ORDER BY owner
    ) LOOP
        BEGIN
            -- Check if POS_BRANCH_SETTING already exists
            SELECT COUNT(*) INTO v_cnt 
            FROM all_tables 
            WHERE owner = s.owner AND table_name = 'POS_BRANCH_SETTING';

            IF v_cnt = 0 THEN
                EXECUTE IMMEDIATE 'CREATE TABLE "' || s.owner || '"."POS_BRANCH_SETTING" (
                    "ID" NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
                    "BRANCH_ID" NUMBER(19) NOT NULL,
                    "DEFAULT_CASH_ACCOUNT" NVARCHAR2(50),
                    "DEFAULT_EXPENSE_ACCOUNT" NVARCHAR2(50),
                    "DEFAULT_RECEIPT_ACCOUNT" NVARCHAR2(50),
                    "DEFAULT_WAREHOUSE_ID" NUMBER(19),
                    "IS_ACTIVE" NUMBER(1) DEFAULT 1 NOT NULL,
                    "CREATION_USER" NVARCHAR2(100) DEFAULT ''SYSTEM'' NOT NULL,
                    "CREATION_DATE" TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
                    "UPDATE_USER" NVARCHAR2(100),
                    "UPDATE_DATE" TIMESTAMP,
                    CONSTRAINT "UQ_POS_BRANCH_SETTING_BRANCH" UNIQUE ("BRANCH_ID"),
                    CONSTRAINT "FK_POS_BRANCH_SETTING_BRANCH" FOREIGN KEY ("BRANCH_ID") 
                        REFERENCES "' || s.owner || '"."SYS_BRANCH"("Id") ON DELETE CASCADE
                )';
            END IF;

            -- Seed default branch setting for Branch 1 if SYS_BRANCH has Branch 1
            EXECUTE IMMEDIATE 'MERGE INTO "' || s.owner || '"."POS_BRANCH_SETTING" dst
            USING (
                SELECT b."Id" AS branch_id, ''111102'' AS cash_acc, ''525101'' AS exp_acc, ''421101'' AS rec_acc
                FROM "' || s.owner || '"."SYS_BRANCH" b
                WHERE b."Id" = 1
            ) src
            ON (dst.BRANCH_ID = src.branch_id)
            WHEN NOT MATCHED THEN
              INSERT (BRANCH_ID, DEFAULT_CASH_ACCOUNT, DEFAULT_EXPENSE_ACCOUNT, DEFAULT_RECEIPT_ACCOUNT, IS_ACTIVE, CREATION_USER, CREATION_DATE)
              VALUES (src.branch_id, src.cash_acc, src.exp_acc, src.rec_acc, 1, ''SYSTEM'', SYSTIMESTAMP)';

        EXCEPTION WHEN OTHERS THEN NULL;
        END;
    END LOOP;

    COMMIT;
END;
/
