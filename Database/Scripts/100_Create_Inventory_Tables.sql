-- 1. Sequences for Documents & Entity Identifiers
-- =============================================================================
DECLARE
    PROCEDURE create_seq_if_not_exists(p_seq_name IN VARCHAR2) IS
        v_count NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_count FROM user_sequences WHERE sequence_name = UPPER(p_seq_name);
        IF v_count = 0 THEN
            EXECUTE IMMEDIATE 'CREATE SEQUENCE ' || p_seq_name || ' START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE';
        END IF;
    END;
BEGIN
    create_seq_if_not_exists('SEQ_TRX_DOC_ID');
    create_seq_if_not_exists('SEQ_INV_COUNT_SESSION_NO');
    create_seq_if_not_exists('SEQ_INV_OPENING_BATCH_NO');
END;
/

