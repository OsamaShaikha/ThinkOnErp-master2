-- Description: Fixes SYS_SYSTEM_SCREEN_FEATURE identity / sequence auto-generation
--              and ensures composite uniqueness on (SYSTEM_ID, NVL(SCREEN_ID, 0), FEATURE_ID).
-- ============================================================================

-- 1. Ensure Sequence Exists
DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM ALL_SEQUENCES WHERE SEQUENCE_NAME = 'SEQ_SYS_SYS_SCREEN_FEATURE' AND SEQUENCE_OWNER = 'THINKON_ERP';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE SEQUENCE THINKON_ERP.SEQ_SYS_SYS_SCREEN_FEATURE START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE';
    END IF;
END;
/

-- 2. Set DEFAULT ON NULL Sequence on THINKON_ERP.SYS_SYSTEM_SCREEN_FEATURE."Id"
BEGIN
    EXECUTE IMMEDIATE 'ALTER TABLE THINKON_ERP.SYS_SYSTEM_SCREEN_FEATURE MODIFY "Id" NUMBER(19) DEFAULT ON NULL THINKON_ERP.SEQ_SYS_SYS_SCREEN_FEATURE.NEXTVAL';
EXCEPTION
    WHEN OTHERS THEN
        NULL;
END;
/

-- 3. Create Trigger TRG_SYS_SYS_SCR_FEAT_ID as Fallback
CREATE OR REPLACE TRIGGER THINKON_ERP.TRG_SYS_SYS_SCR_FEAT_ID
BEFORE INSERT ON THINKON_ERP.SYS_SYSTEM_SCREEN_FEATURE
FOR EACH ROW
BEGIN
    IF :NEW."Id" IS NULL OR :NEW."Id" <= 0 THEN
        :NEW."Id" := THINKON_ERP.SEQ_SYS_SYS_SCREEN_FEATURE.NEXTVAL;
    END IF;
END;
/

-- 4. Ensure Composite Unique Index on THINKON_ERP.SYS_SYSTEM_SCREEN_FEATURE
DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM ALL_INDEXES WHERE INDEX_NAME = 'IX_SYS_SYS_SCR_FEAT_UK' AND OWNER = 'THINKON_ERP';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE UNIQUE INDEX THINKON_ERP.IX_SYS_SYS_SCR_FEAT_UK ON THINKON_ERP.SYS_SYSTEM_SCREEN_FEATURE(SYSTEM_ID, NVL(SCREEN_ID, 0), FEATURE_ID)';
    END IF;
END;
/

-- 5. Ensure Composite Unique Index on DEV_TEMPLATE.SYS_SYSTEM_SCREEN_FEATURE
DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM ALL_INDEXES WHERE INDEX_NAME = 'IX_SYS_SYS_SCR_FEAT_UK' AND OWNER = 'DEV_TEMPLATE';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE UNIQUE INDEX DEV_TEMPLATE.IX_SYS_SYS_SCR_FEAT_UK ON DEV_TEMPLATE.SYS_SYSTEM_SCREEN_FEATURE(SYSTEM_ID, NVL(SCREEN_ID, 0), FEATURE_ID)';
    END IF;
END;
/
