-- ============================================================================
-- Script: 124_Convert_SYS_SCREEN_To_Many_To_Many_With_SYS_SYSTEM.sql
-- Description: Converts the 1:M relationship between SYS_SYSTEM and SYS_SCREEN
--              to a Many-to-Many (M:M) relationship via SYS_SYSTEM_SCREEN.
-- ============================================================================

-- 1. Create Sequence for SYS_SYSTEM_SCREEN
DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM USER_SEQUENCES WHERE SEQUENCE_NAME = 'SEQ_SYS_SYSTEM_SCREEN';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE SEQUENCE SEQ_SYS_SYSTEM_SCREEN START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE';
    END IF;
END;
/

-- 2. Create SYS_SYSTEM_SCREEN Table
DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM USER_TABLES WHERE TABLE_NAME = 'SYS_SYSTEM_SCREEN';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE TABLE SYS_SYSTEM_SCREEN (
                "Id" NUMBER(19) PRIMARY KEY,
                SYSTEM_ID NUMBER(19) NOT NULL,
                SCREEN_ID NUMBER(19) NOT NULL,
                PARENT_SCREEN_ID NUMBER(19),
                DISPLAY_ORDER NUMBER(10) DEFAULT 0,
                IS_ACTIVE NUMBER(1) DEFAULT 1 CHECK (IS_ACTIVE IN (0, 1)),
                CREATION_USER NVARCHAR2(100) NOT NULL,
                CREATION_DATE DATE DEFAULT SYSDATE,
                UPDATE_USER NVARCHAR2(100),
                UPDATE_DATE DATE,
                CONSTRAINT FK_SYS_SCREEN_SYS FOREIGN KEY (SYSTEM_ID) REFERENCES SYS_SYSTEM("Id") ON DELETE CASCADE,
                CONSTRAINT FK_SYS_SCREEN_SCR FOREIGN KEY (SCREEN_ID) REFERENCES SYS_SCREEN("Id") ON DELETE CASCADE,
                CONSTRAINT FK_SYS_SCREEN_PAR FOREIGN KEY (PARENT_SCREEN_ID) REFERENCES SYS_SCREEN("Id") ON DELETE SET NULL,
                CONSTRAINT UK_SYS_SYSTEM_SCREEN UNIQUE (SYSTEM_ID, SCREEN_ID)
            )';
    END IF;
END;
/

-- 3. Create Supporting Indexes
DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM USER_INDEXES WHERE INDEX_NAME = 'IDX_SYS_SYSTEM_SCREEN_SYS';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX IDX_SYS_SYSTEM_SCREEN_SYS ON SYS_SYSTEM_SCREEN(SYSTEM_ID)';
    END IF;

    SELECT COUNT(*) INTO v_count FROM USER_INDEXES WHERE INDEX_NAME = 'IDX_SYS_SYSTEM_SCREEN_SCR';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX IDX_SYS_SYSTEM_SCREEN_SCR ON SYS_SYSTEM_SCREEN(SCREEN_ID)';
    END IF;
END;
/

-- 4. Migrate Existing 1:M Data into SYS_SYSTEM_SCREEN
DECLARE
    v_inserted NUMBER := 0;
BEGIN
    FOR r IN (
        SELECT s."Id" AS SCREEN_ID, s.SYSTEM_ID, s.PARENT_SCREEN_ID, s.DISPLAY_ORDER, s.IS_ACTIVE, s.CREATION_USER
        FROM SYS_SCREEN s
        WHERE s.SYSTEM_ID IS NOT NULL
          AND NOT EXISTS (
              SELECT 1 FROM SYS_SYSTEM_SCREEN ss
              WHERE ss.SYSTEM_ID = s.SYSTEM_ID AND ss.SCREEN_ID = s."Id"
          )
    ) LOOP
        INSERT INTO SYS_SYSTEM_SCREEN (
            "Id", SYSTEM_ID, SCREEN_ID, PARENT_SCREEN_ID, DISPLAY_ORDER, IS_ACTIVE, CREATION_USER, CREATION_DATE
        ) VALUES (
            SEQ_SYS_SYSTEM_SCREEN.NEXTVAL,
            r.SYSTEM_ID,
            r.SCREEN_ID,
            r.PARENT_SCREEN_ID,
            NVL(r.DISPLAY_ORDER, 0),
            NVL(r.IS_ACTIVE, 1),
            NVL(r.CREATION_USER, 'MIGRATION'),
            SYSDATE
        );
        v_inserted := v_inserted + 1;
    END LOOP;
    COMMIT;
    DBMS_OUTPUT.PUT_LINE('Migrated ' || v_inserted || ' screen-system associations.');
END;
/

-- 5. Modify SYS_SCREEN.SYSTEM_ID to Nullable (for backward compatibility)
BEGIN
    EXECUTE IMMEDIATE 'ALTER TABLE SYS_SCREEN MODIFY SYSTEM_ID NUMBER(19) NULL';
EXCEPTION
    WHEN OTHERS THEN
        NULL; -- Ignore if already nullable
END;
/

-- 6. Update Procedure SP_SYS_SCREEN_GET_BY_SYSTEM
CREATE OR REPLACE PROCEDURE SP_SYS_SCREEN_GET_BY_SYSTEM(
    P_SYSTEM_ID IN NUMBER,
    P_RESULT_CURSOR OUT SYS_REFCURSOR
)
AS
BEGIN
    OPEN P_RESULT_CURSOR FOR
    SELECT s."Id" AS "Id", 
           P_SYSTEM_ID AS SYSTEM_ID, 
           COALESCE(ss.PARENT_SCREEN_ID, s.PARENT_SCREEN_ID) AS PARENT_SCREEN_ID, 
           s.SCREEN_CODE, 
           s.SCREEN_NAME, 
           s.SCREEN_NAME_E,
           s.ROUTE, 
           s.DESCRIPTION, 
           s.DESCRIPTION_E, 
           s.ICON, 
           COALESCE(ss.DISPLAY_ORDER, s.DISPLAY_ORDER) AS DISPLAY_ORDER, 
           s.IS_ACTIVE,
           s.CREATION_USER, 
           s.CREATION_DATE, 
           s.UPDATE_USER, 
           s.UPDATE_DATE
    FROM SYS_SCREEN s
    INNER JOIN SYS_SYSTEM_SCREEN ss ON ss.SCREEN_ID = s."Id"
    WHERE ss.SYSTEM_ID = P_SYSTEM_ID
      AND ss.IS_ACTIVE = 1
      AND s.IS_ACTIVE = 1
    ORDER BY COALESCE(ss.DISPLAY_ORDER, s.DISPLAY_ORDER), s.SCREEN_NAME;
END;
/

-- 7. Update Function FN_CHECK_USER_PERMISSION for M:M Support
CREATE OR REPLACE FUNCTION FN_CHECK_USER_PERMISSION(
    P_USER_ID IN NUMBER,
    P_SCREEN_CODE IN NVARCHAR2,
    P_ACTION IN VARCHAR2  -- 'VIEW', 'INSERT', 'UPDATE', 'DELETE'
) RETURN CHAR
IS
    V_IS_SUPER_ADMIN CHAR(1);
    V_IS_ACTIVE NUMBER;
    V_COMPANY_ID NUMBER;
    V_SCREEN_ID NUMBER;
    V_SYSTEM_ALLOWED NUMBER;
    V_USER_OVERRIDE_COUNT NUMBER;
    V_USER_PERMISSION CHAR(1);
    V_ROLE_PERMISSION CHAR(1) := '0';
BEGIN
    -- Check if user is Super Admin
    SELECT IS_SUPER_ADMIN, IS_ACTIVE, COMPANY_ID
    INTO V_IS_SUPER_ADMIN, V_IS_ACTIVE, V_COMPANY_ID
    FROM SYS_USERS
    WHERE "Id" = P_USER_ID;
    
    IF V_IS_SUPER_ADMIN = '1' THEN
        RETURN '1';
    END IF;
    
    IF V_IS_ACTIVE != 1 THEN
        RETURN '0';
    END IF;
    
    -- Get screen ID
    SELECT s."Id"
    INTO V_SCREEN_ID
    FROM SYS_SCREEN s
    WHERE s.SCREEN_CODE = P_SCREEN_CODE AND s.IS_ACTIVE = 1;
    
    -- Check if ANY of the screen's systems are allowed for company
    SELECT COUNT(*)
    INTO V_SYSTEM_ALLOWED
    FROM SYS_COMPANY_SYSTEM cs
    INNER JOIN SYS_BRANCH b ON cs.COMPANY_ID = b.PAR_ROW_ID
    INNER JOIN SYS_SYSTEM_SCREEN ss ON ss.SYSTEM_ID = cs.SYSTEM_ID
    WHERE b."Id" = V_COMPANY_ID
      AND ss.SCREEN_ID = V_SCREEN_ID
      AND ss.IS_ACTIVE = 1
      AND cs.IS_ALLOWED = '1';
    
    IF V_SYSTEM_ALLOWED = 0 THEN
        -- Fallback to legacy SYS_SCREEN.SYSTEM_ID if not yet in SYS_SYSTEM_SCREEN
        SELECT COUNT(*)
        INTO V_SYSTEM_ALLOWED
        FROM SYS_COMPANY_SYSTEM cs
        INNER JOIN SYS_BRANCH b ON cs.COMPANY_ID = b.PAR_ROW_ID
        INNER JOIN SYS_SCREEN s ON s.SYSTEM_ID = cs.SYSTEM_ID
        WHERE b."Id" = V_COMPANY_ID
          AND s."Id" = V_SCREEN_ID
          AND cs.IS_ALLOWED = '1';
          
        IF V_SYSTEM_ALLOWED = 0 THEN
            RETURN '0';
        END IF;
    END IF;
    
    -- Check direct user permission override
    SELECT COUNT(*)
    INTO V_USER_OVERRIDE_COUNT
    FROM SYS_USER_SCREEN_PERMISSION
    WHERE USER_ID = P_USER_ID AND SCREEN_ID = V_SCREEN_ID;
    
    IF V_USER_OVERRIDE_COUNT > 0 THEN
        IF P_ACTION = 'VIEW' THEN
            SELECT CAN_VIEW INTO V_USER_PERMISSION FROM SYS_USER_SCREEN_PERMISSION WHERE USER_ID = P_USER_ID AND SCREEN_ID = V_SCREEN_ID;
        ELSIF P_ACTION = 'INSERT' THEN
            SELECT CAN_INSERT INTO V_USER_PERMISSION FROM SYS_USER_SCREEN_PERMISSION WHERE USER_ID = P_USER_ID AND SCREEN_ID = V_SCREEN_ID;
        ELSIF P_ACTION = 'UPDATE' THEN
            SELECT CAN_UPDATE INTO V_USER_PERMISSION FROM SYS_USER_SCREEN_PERMISSION WHERE USER_ID = P_USER_ID AND SCREEN_ID = V_SCREEN_ID;
        ELSIF P_ACTION = 'DELETE' THEN
            SELECT CAN_DELETE INTO V_USER_PERMISSION FROM SYS_USER_SCREEN_PERMISSION WHERE USER_ID = P_USER_ID AND SCREEN_ID = V_SCREEN_ID;
        ELSE
            RETURN '0';
        END IF;
        
        RETURN V_USER_PERMISSION;
    END IF;
    
    -- Check role permissions
    FOR r IN (
        SELECT ur.ROLE_ID
        FROM SYS_USER_ROLE ur
        INNER JOIN SYS_ROLE ro ON ur.ROLE_ID = ro."Id"
        WHERE ur.USER_ID = P_USER_ID AND ro.IS_ACTIVE = 1
    ) LOOP
        DECLARE
            V_TEMP_PERM CHAR(1) := '0';
        BEGIN
            IF P_ACTION = 'VIEW' THEN
                SELECT NVL(MAX(CAN_VIEW), '0') INTO V_TEMP_PERM FROM SYS_ROLE_SCREEN_PERMISSION WHERE ROLE_ID = r.ROLE_ID AND SCREEN_ID = V_SCREEN_ID;
            ELSIF P_ACTION = 'INSERT' THEN
                SELECT NVL(MAX(CAN_INSERT), '0') INTO V_TEMP_PERM FROM SYS_ROLE_SCREEN_PERMISSION WHERE ROLE_ID = r.ROLE_ID AND SCREEN_ID = V_SCREEN_ID;
            ELSIF P_ACTION = 'UPDATE' THEN
                SELECT NVL(MAX(CAN_UPDATE), '0') INTO V_TEMP_PERM FROM SYS_ROLE_SCREEN_PERMISSION WHERE ROLE_ID = r.ROLE_ID AND SCREEN_ID = V_SCREEN_ID;
            ELSIF P_ACTION = 'DELETE' THEN
                SELECT NVL(MAX(CAN_DELETE), '0') INTO V_TEMP_PERM FROM SYS_ROLE_SCREEN_PERMISSION WHERE ROLE_ID = r.ROLE_ID AND SCREEN_ID = V_SCREEN_ID;
            END IF;
            
            IF V_TEMP_PERM = '1' THEN
                V_ROLE_PERMISSION := '1';
                EXIT;
            END IF;
        END;
    END LOOP;
    
    RETURN V_ROLE_PERMISSION;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RETURN '0';
    WHEN OTHERS THEN
        RETURN '0';
END;
/

COMMENT ON TABLE SYS_SYSTEM_SCREEN IS 'Many-to-many relationship mapping screens to one or more systems';
COMMENT ON COLUMN SYS_SYSTEM_SCREEN.SYSTEM_ID IS 'Foreign key to SYS_SYSTEM table';
COMMENT ON COLUMN SYS_SYSTEM_SCREEN.SCREEN_ID IS 'Foreign key to SYS_SCREEN table';
COMMENT ON COLUMN SYS_SYSTEM_SCREEN.DISPLAY_ORDER IS 'Display order of this screen within this specific system';
COMMENT ON COLUMN SYS_SYSTEM_SCREEN.PARENT_SCREEN_ID IS 'Optional parent screen within this specific system hierarchy';
