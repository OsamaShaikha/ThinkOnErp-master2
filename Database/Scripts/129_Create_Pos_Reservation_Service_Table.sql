-- ==============================================================================
-- 129_Create_Pos_Reservation_Service_Table.sql
-- Creates POS_RESERVATION_SERVICE table to support multi-service bookings,
-- service duration, delay/buffer times, and per-service staff assignment.
-- ==============================================================================

SET SERVEROUTPUT ON SIZE UNLIMITED;
SET FEEDBACK OFF;

DECLARE
    v_table_count NUMBER;
    v_schemas_processed NUMBER := 0;
BEGIN
    DBMS_OUTPUT.PUT_LINE('Starting migration for POS_RESERVATION_SERVICE table...');

    FOR t IN (
        SELECT owner 
        FROM all_tables 
        WHERE table_name = 'POS_RESERVATION' 
          AND (owner = 'THINKON_ERP' OR owner = 'DEV_TEMPLATE' OR owner LIKE 'THINKONERP_%' OR owner = '1')
        ORDER BY owner
    ) LOOP
        DBMS_OUTPUT.PUT_LINE('>>> Schema: ' || t.owner);
        v_schemas_processed := v_schemas_processed + 1;

        SELECT COUNT(*) INTO v_table_count
        FROM all_tables
        WHERE owner = t.owner AND table_name = 'POS_RESERVATION_SERVICE';

        IF v_table_count = 0 THEN
            BEGIN
                EXECUTE IMMEDIATE 'CREATE TABLE "' || t.owner || '"."POS_RESERVATION_SERVICE" (
                    "ID" NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
                    "RESERVATION_ID" NUMBER(19) NOT NULL,
                    "SERVICE_ITEM_ID" NUMBER(19) NOT NULL,
                    "SERVICE_NAME" NVARCHAR2(150) NOT NULL,
                    "DURATION_MINUTES" NUMBER(10) DEFAULT 30 NOT NULL,
                    "DELAY_MINUTES" NUMBER(10) DEFAULT 0 NOT NULL,
                    "START_TIME" INTERVAL DAY(8) TO SECOND(7) NOT NULL,
                    "END_TIME" INTERVAL DAY(8) TO SECOND(7) NOT NULL,
                    "PRIMARY_STAFF_ID" NUMBER(19),
                    "PRIMARY_STAFF_NAME" NVARCHAR2(150),
                    "ADDITIONAL_STAFF_IDS" NVARCHAR2(200),
                    "PRICE" NUMBER(18,4) DEFAULT 0.0 NOT NULL,
                    "NOTES" NVARCHAR2(500),
                    "SORT_ORDER" NUMBER(10) DEFAULT 1 NOT NULL,
                    CONSTRAINT "PK_POS_RES_SERVICE" PRIMARY KEY ("ID"),
                    CONSTRAINT "FK_POS_RES_SERV_RES" FOREIGN KEY ("RESERVATION_ID") 
                        REFERENCES "' || t.owner || '"."POS_RESERVATION" ("ID") ON DELETE CASCADE
                )';
                DBMS_OUTPUT.PUT_LINE('    + Created table POS_RESERVATION_SERVICE');
            EXCEPTION WHEN OTHERS THEN
                DBMS_OUTPUT.PUT_LINE('    ! Error creating table: ' || SQLERRM);
            END;

            BEGIN
                EXECUTE IMMEDIATE 'CREATE INDEX "' || t.owner || '"."IX_POS_RES_SERV_RES_ID" ON "' || t.owner || '"."POS_RESERVATION_SERVICE" ("RESERVATION_ID")';
                DBMS_OUTPUT.PUT_LINE('    + Created index IX_POS_RES_SERV_RES_ID');
            EXCEPTION WHEN OTHERS THEN NULL;
            END;

            BEGIN
                EXECUTE IMMEDIATE 'CREATE INDEX "' || t.owner || '"."IX_POS_RES_SERV_STAFF_ID" ON "' || t.owner || '"."POS_RESERVATION_SERVICE" ("PRIMARY_STAFF_ID")';
                DBMS_OUTPUT.PUT_LINE('    + Created index IX_POS_RES_SERV_STAFF_ID');
            EXCEPTION WHEN OTHERS THEN NULL;
            END;
        ELSE
            DBMS_OUTPUT.PUT_LINE('    = Table POS_RESERVATION_SERVICE already exists');
        END IF;
    END LOOP;

    DBMS_OUTPUT.PUT_LINE('---------------------------------------------');
    DBMS_OUTPUT.PUT_LINE('Completed successfully! Total schemas processed: ' || v_schemas_processed);
END;
/

EXIT;
